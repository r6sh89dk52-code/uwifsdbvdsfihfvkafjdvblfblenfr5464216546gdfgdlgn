const assert=require('node:assert/strict');
const {load,parse,all,value}=require('./ambulatory-test-helpers.cjs');
const {unzipSync,strFromU8}=require('fflate');
const shared=load('src/sharedInventoryReports.ts'),stock=load('src/kardexMovements.ts');
const daily=load('src/dailyKardex.ts'),excel=load('src/ambulatoryExcel.ts');
const products=require('../src/products.json'),template=require('../src/ambulatoryTemplate.json');
const catalog=load('src/kardexCatalog.ts').kardexCatalog;
const iso=(s)=>Date.parse(s),product=(code)=>catalog.find(x=>x.id===code);
const mk=(code,id,n,date)=>({code,id,name:product(code).name,lot:id,catalogUnit:'UND',expires:'2028-12-30',container:'unidad',unitsPerContainer:1,sealedContainers:0,looseUnits:n,openedRemaining:0,updatedAt:iso(date)});
const mkPlan=(start,end,code,qty)=>{
 const cells=Array(30).fill('');
 if(qty){cells[15]=code;cells[16]=products.find(x=>x.code===code).name;cells[17]=qty}
 return{start,end,lines:qty?[{id:'fake',cells}]:[],visits:0,linkedDeliveries:qty?1:0,blockers:[],warnings:[]};
};
assert.equal(shared.reportMonth('2026-09').start,'2026-09-09');
assert.equal(shared.reportMonth('2026-09').end,'2026-10-08');
assert.equal(shared.reportMonth('2026-12').end,'2027-01-08');
assert.equal(shared.currentReportMonth(new Date('2026-10-08T12:00:00Z')),'2026-09');
assert.equal(shared.currentReportMonth(new Date('2026-10-09T12:00:00Z')),'2026-10');
const code='16000182',at=iso('2026-10-01T16:00:00Z');
let ledger={lots:[mk('E-22','p',50,'2026-09-09T13:00:00Z')],movements:[]};
const ref={attentionId:'a',itemId:'i',clinicalCode:code,clinicalName:products.find(x=>x.code===code).name,clinicalUnit:'UND',clinicalQuantity:20,confirmedAt:at};
ledger=stock.postStockMovement(ledger,{id:'ATT:a:ITEM:i',lotId:'p',at,kind:'use',description:'Entrega confirmada ficticia',quantity:20,dispenseRef:ref});
assert.equal(daily.buildDailyReport(ledger,'2026-10-01').rows[21].final,30);
assert.equal(daily.buildDailyReport(ledger,'2026-10-02').rows[21].initial,30);
const range=daily.buildKardexRangeReport(ledger,'2026-10-01','2026-10-02');
assert.equal(range.rows[21].initial,50);assert.equal(range.rows[21].final,30);assert.equal(range.exportable,true);
let p=mkPlan('2026-09-09','2026-10-08',code,20);
let result=shared.sharedMonthlyReconciliation(ledger,p);
assert.equal(result.byCode[code].opening,50);
assert.equal(result.byCode[code].receipts,0);
assert.equal(result.byCode[code].closing,30);
assert.equal(result.byCode[products[0].code].opening,undefined);
p=mkPlan('2026-10-09','2026-11-08',code,0);
result=shared.sharedMonthlyReconciliation(ledger,p);
assert.equal(result.byCode[code].opening,30);
assert.equal(result.byCode[code].closing,undefined,'no future monthly closing');
assert.equal(result.byCode[code].receipts,undefined,'no invented future zero');
const pairs={lots:[mk('E-62','a',5,'2026-09-09T15:00:00Z'),mk('E-63','b',7,'2026-09-09T15:00:00Z')],movements:[]};
assert.equal(shared.sharedMonthlyReconciliation(pairs,mkPlan('2026-09-09','2026-10-08','16024400',0)).byCode['16024400'].opening,12);
const late={lots:[mk('E-22','late',25,'2026-09-10T14:00:00Z')],movements:[]};
assert.equal(shared.sharedMonthlyReconciliation(late,mkPlan('2026-09-09','2026-10-08',code,0)).byCode[code].opening,undefined);
const source=Uint8Array.from(atob(template.zipBase64),c=>c.charCodeAt(0));
const cut=mkPlan('2026-09-09','2026-10-08',code,20);
const archive=unzipSync(excel.exportAmbulatoryWorkbook(source,cut,shared.sharedMonthlyReconciliation(ledger,cut)));
const w=parse(strFromU8(archive['xl/workbook.xml']));
assert.deepEqual(all(w,'sheet').map(x=>x.getAttribute('name')),template.sheets);
assert.equal(Object.keys(archive).filter(x=>/^xl\/tables\/table\d+\.xml$/.test(x)).length,19);
const resu=parse(strFromU8(archive['xl/worksheets/sheet4.xml']));
const row=products.findIndex(x=>x.code===code)+3;
assert.equal(value(all(resu,'c').find(x=>x.getAttribute('r')==='D'+row)),'50');
console.log('PASS: 9-to-8 month, daily 50→30 carryover, no invented future, 10 sheets and original 19 Excel tables.');
