const assert=require('node:assert/strict');
const fs=require('node:fs');
const {load,visit,options,parse,all,value}=require('./ambulatory-test-helpers.cjs');
const {unzipSync,strFromU8}=require('fflate');
const products=require('../src/products.json');
const {buildAmbulatoryRows}=load('src/ambulatoryRows.ts');
const {exportAmbulatoryWorkbook}=load('src/ambulatoryExcel.ts');
const {sharedMonthlyReconciliation}=load('src/sharedInventoryReports.ts');
const {postConfirmedAttentionDelivery}=load('src/attentionKardex.ts');
const template=new Uint8Array(fs.readFileSync('scripts/fixtures/ambulatory-empty.xlsx'));
const p=products.find(p=>p.code==='16000182');
const q=products.find(p=>p.code==='16000013');
assert(p&&q);
const pendingItem={id:'pending-item',...q,quantity:1,procedure:'CURACION'};
const confirmedItem={id:'confirmed-item',...p,quantity:1,procedure:'TRATAMIENTO ORAL'};
const baseline=visit('attention-ficticia',[pendingItem,confirmedItem]);
baseline.worker.site='LA VENTUROSA';
const inventory={lots:[],movements:[]};
const inputBefore=JSON.stringify([baseline,inventory]);
const strict=buildAmbulatoryRows([baseline],inventory,'2026-10-09','2026-11-08',{perVisitSubdivision:true});
assert.equal(strict.blockers.length,2,'two pending deliveries block the official report');
assert.throws(()=>exportAmbulatoryWorkbook(template,strict),/pendientes/);
const provisional=buildAmbulatoryRows([baseline],inventory,'2026-10-09','2026-11-08',{perVisitSubdivision:true,allowPendingDeliveries:true});
assert.equal(provisional.provisional,true);
assert.equal(provisional.pendingDeliveries,2);
assert.equal(provisional.visits,1);
assert.equal(provisional.blockers.length,0);
assert.deepEqual(provisional.lines.map(l=>l.cells[17]),['',''],'R must be blank, never a guessed zero/negative');
assert.deepEqual(provisional.lines.map(l=>l.cells[15]),[q.code,p.code],'keep clinical supply codes');
assert.deepEqual(provisional.lines.map(l=>l.cells[16]),[q.name,p.name],'keep clinical supply names');
assert.ok(provisional.warnings.some(w=>w.includes('BORRADOR PROVISIONAL')));
const cut=sharedMonthlyReconciliation(inventory,provisional);
assert.equal(cut.openingConfirmed,0,'no fabricated opening balances');
assert.equal(cut.byCode[q.code].opening,undefined);
assert.equal(cut.byCode[p.code].opening,undefined);
const xlsx=exportAmbulatoryWorkbook(template,provisional,cut);
const files=unzipSync(xlsx);
const sheets=parse(strFromU8(files['xl/workbook.xml']));
assert.equal(all(sheets,'sheet').length,10);
const rows=parse(strFromU8(files['xl/worksheets/sheet5.xml']));
const cell=(ref)=>all(rows,'c').find(x=>x.getAttribute('r')===ref);
assert.equal(value(cell('P2')),q.code);
assert.equal(value(cell('Q2')),q.name);
assert.equal(value(cell('R2')),'');
assert.equal(value(cell('R3')),'');
const resu=parse(strFromU8(files['xl/worksheets/sheet4.xml']));
const rcell=(ref)=>all(resu,'c').find(x=>x.getAttribute('r')===ref);
assert.equal(value(rcell('D3')),'','unknown initial balance not set to 0');
assert.equal(value(rcell('M3')),'','preserve manual comment');
assert.ok(all(rcell('F3'),'f').length===1,'RESU formulas remain intact');
const notTagged={...provisional,provisional:false};
assert.throws(()=>exportAmbulatoryWorkbook(template,notTagged,cut),/no verificados/,'blank R illegal in strict export');
const neg={...provisional,lines:provisional.lines.map((row,i)=>i===0?{...row,cells:row.cells.map((v,j)=>j===17?-1:v)}:row)};
assert.throws(()=>exportAmbulatoryWorkbook(template,neg,cut),/no verificados/,'negative R rejected even in provisional');
const unknown={...baseline,worker:{...baseline.worker,site:''}};
assert.ok(buildAmbulatoryRows([unknown],inventory,'2026-10-09','2026-11-08',{perVisitSubdivision:true,allowPendingDeliveries:true}).blockers.length,'missing official site still blocked');
// Mix confirmed and pending deliveries: confirmed R remains audited; missing R stays blank.
const nursing=load('src/kardexCatalog.ts').kardexCatalog.find(x=>x.id==='E-22');
const first={...visit('confirmed-ficticio',[confirmedItem]),worker:{...visit().worker,site:'LA VENTUROSA'}};
const ts=Date.parse('2026-10-14T15:00:00Z');
const lot={id:'lot-ficticio',code:nursing.id,name:nursing.name,catalogUnit:'UND',lot:'TEST-2026',
 expires:'2027-12-01',container:'unidad',unitsPerContainer:1,sealedContainers:0,looseUnits:20,openedRemaining:0,updatedAt:ts-100000};
const delivered=postConfirmedAttentionDelivery({lots:[lot],movements:[]},first,{itemId:confirmedItem.id,lotId:lot.id,physicalQuantity:1,confirmIdentity:true,confirmUnits:true,confirmDelivery:true,openNewContainer:false,timestamp:ts});
const mixed=buildAmbulatoryRows([first,baseline],delivered,'2026-10-09','2026-11-08',{perVisitSubdivision:true,allowPendingDeliveries:true});
assert.equal(mixed.pendingDeliveries,2);
assert.ok(mixed.lines.some(x=>x.cells[17]===1),'audited R remains');
assert.equal(mixed.lines.filter(x=>x.cells[17]==='').length,2,'only pending quantities blank');
assert.equal(JSON.stringify([baseline,inventory]),inputBefore,'export never changes clinical records nor stock');
const ui=fs.readFileSync('src/AmbulatoryExportPanel.tsx','utf8');
assert.match(ui,/canDraft/);
assert.match(ui,/PROVISIONAL_PENDIENTE_CONCILIACION/);
assert.match(ui,/window.confirm\('EXCEL PROVISIONAL/);
assert.match(ui,/result.data.blockers.every/,'only specifically unlinked deliveries may be bypassed');
const workflow=fs.readFileSync('.github/workflows/ios-ipa.yml','utf8');
assert.match(workflow,/workflow_dispatch/);
assert.doesNotMatch(workflow,/^\s*(push|pull_request):/m,'no automatic macOS builds');
console.log('PASS: strict default, provisional ten sheets, blank unverified R, no fake zeros/negative stock, known deliveries preserved, missing-site blocker, no writes, Linux-only.');
