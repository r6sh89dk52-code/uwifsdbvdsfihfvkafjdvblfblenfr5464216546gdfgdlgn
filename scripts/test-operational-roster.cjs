const assert=require('node:assert/strict');
const fs=require('node:fs'),vm=require('node:vm'),ts=require('typescript');
function load(path,mods={}){
 const module={exports:{}};
 const js=ts.transpileModule(fs.readFileSync(path,'utf8'),{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2022}}).outputText;
 vm.runInNewContext(js,{module,exports:module.exports,require:(key)=>{if(!(key in mods))throw Error('Unexpected module '+key);return mods[key]},Set,Map,Error,Array,Number,String,Object,Math},{filename:path});
 return module.exports;
}
const rules=load('src/workerRules.ts');
const review=load('src/officialRosterReview.ts',{'./workerRules':rules});
const roster=load('src/operationalRoster.ts',{'./workerRules':rules,'./officialRosterReview':review});
const row=(dni,name,source='imported')=>({dni:String(dni).padStart(8,'0'),name,area:'FUNDO',labor:'TRABAJADOR',sex:'',age:'',ubigeo:'',source});
const fictitious=Array.from({length:9000},(_,i)=>row(i+1000000,'PRUEBA '+i));
const real=Array.from({length:9000},(_,i)=>row(i+3000000,'REAL '+i));
const old=[...fictitious,...real];
const historical=[fictitious[0]];
assert.equal(roster.officialRosterActive(old),false);
assert.equal(roster.searchableWorkers(old,historical).length,18000);
const prepared=roster.prepareOfficialRoster(old,real,[fictitious[0].dni]);
assert.equal(prepared.workers.length,18000);
assert.equal(prepared.officialCount,9000);
assert.equal(prepared.excludedCount,9000);
assert.equal(prepared.review.protectedLinked,1);
assert.equal(roster.officialRosterActive(prepared.workers),true);
const visible=roster.searchableWorkers(prepared.workers,historical);
assert.equal(visible.length,9000);
assert.ok(visible.every(w=>w.rosterStatus==='official'));
assert.ok(!visible.some(w=>w.dni===fictitious[0].dni));
assert.equal(old.length,18000);
assert.equal(old[0].rosterStatus,undefined);
const repeated=roster.prepareOfficialRoster(prepared.workers,real,[]);
assert.equal(repeated.officialCount,9000);
assert.equal(repeated.workers.length,18000);
const newManual=row(50000000,'MANUAL','manual');newManual.rosterStatus='pending';
const withPending=[...prepared.workers,newManual];
assert.equal(roster.searchableWorkers(withPending,historical).length,9000);
const verified={...newManual,rosterStatus:'verified'};
const withVerified=[...prepared.workers,verified];
assert.equal(roster.searchableWorkers(withVerified,historical).length,9001);
const refreshed=roster.prepareOfficialRoster(withVerified,real,[]);
assert.equal(refreshed.manualVerifiedCount,1);
assert.equal(roster.searchableWorkers(refreshed.workers,historical).length,9001);
assert.throws(()=>roster.prepareOfficialRoster(prepared.workers,real.slice(0,1500)),/80 %/);
assert.throws(()=>roster.prepareOfficialRoster(old,[real[0],real[0]]),/repetidos/);
assert.throws(()=>roster.prepareOfficialRoster(old,[]),/vacía/);
assert.equal(roster.searchableWorkers(prepared.workers,[...historical,...historical]).length,9000);
console.log('PASS: 18.000 usuarios ficticios/reales; filtro oficial 9.000, reimportación, pendientes, verificados, historial preservado, archivo incompleto bloqueado.');
