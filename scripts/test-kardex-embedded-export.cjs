const assert=require('node:assert/strict');
const fs=require('node:fs');
const ts=require('typescript');
const {unzipSync,strFromU8}=require('fflate');
const {DOMParser,XMLSerializer}=require('@xmldom/xmldom');
const {load}=require('./ambulatory-test-helpers.cjs');
const NS='http://schemas.openxmlformats.org/spreadsheetml/2006/main';
const bytes=new Uint8Array(fs.readFileSync('public/internal/kardex-template.bin'));
const original=unzipSync(bytes);
const source=fs.readFileSync('src/kardexExcelTemplate.ts','utf8');
const compiled=ts.transpileModule(source,{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2022}}).outputText;
const m={exports:{}};
new Function('require','module','exports','DOMParser','XMLSerializer',compiled)(name=>name==='fflate'?require('fflate'):{},m,m.exports,DOMParser,XMLSerializer);
const products=load('src/kardexCatalog.ts').kardexCatalog;
assert.equal(products.length,98);
const rows=products.map((p,i)=>({code:p.id,name:p.name,donated:false,stockKnown:i<2,initial:i===0?3:0,extraordinary:0,total:i===0?3:0,consumed:i===0?1:0,final:i===0?2:0,expiry:'',fs:null}));
const report={date:'2026-10-13',rows,exportable:true,warnings:[]};
const output=unzipSync(m.exports.exportOfficialKardex(bytes,report,'MAÑANA','PERSONA FICTICIA'));
assert.deepEqual(Object.keys(output).sort(),Object.keys(original).sort());
const sheet=strFromU8(output['xl/worksheets/sheet2.xml']);
const doc=new DOMParser().parseFromString(sheet,'application/xml');
const cell=ref=>Array.from(doc.getElementsByTagNameNS(NS,'c')).find(c=>c.getAttribute('r')===ref);
const val=ref=>cell(ref)?.getElementsByTagNameNS(NS,'v')[0]?.textContent;
const formula=ref=>cell(ref)?.getElementsByTagNameNS(NS,'f')[0]?.textContent;
assert.equal(val('D7'),'3');assert.equal(val('G7'),'1');assert.equal(val('H7'),'2');
assert.equal(formula('F7'),'D7+E7');assert.equal(formula('H7'),'F7-G7');
assert.equal(val('D8'),'0');assert.equal(val('D9'),undefined);
assert.ok(cell('C104'));
assert.ok(output['xl/printerSettings/printerSettings2.bin']);
assert.ok(sheet.includes('orientation="portrait"')&&sheet.includes('scale="90"'));
assert.throws(()=>m.exports.exportOfficialKardex(bytes,{...report,exportable:false},'MAÑANA','TEST'),/observaciones/);
console.log('PASS: plantilla interna real, 98 productos, formulas, saldos desconocidos y propiedades A4 90%.');
