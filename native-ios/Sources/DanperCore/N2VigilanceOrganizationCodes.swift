    private static let official:[String:[String:String]] = {
        var all=[String:[String:String]]()
        for row in officialRows.split(separator:"\n") {
            let p=row.split(separator:"|",omittingEmptySubsequences:false)
            guard p.count==3 else{continue}
            all[String(p[0]),default:[:]][normalize(String(p[1]))]=String(p[2])
        }
        return all
    }()
    public static func resolve(site:String,unit:String,
                               existingSubdivision:String="",
                               existingOrganization:String="")->Resolution {
        guard let (society,subdivision)=society(site) else {
            // Unknown site: do not assign Venturosa codes to it.
            return Resolution(subdivision:existingSubdivision,
                              organizationalUnit:existingOrganization,
                              recognizedSite:false)
        }
        let key=normalize(unit)
        let mapped=official[society]?[key]
        // A documented code is retained only if it belongs to this
        // society AND the area is unknown (e.g. an old historical visit).
        // Conflicting or unverified codes are never silently presented.
        let known=Set(official[society]?.values.map{Array($0)} ?? [])
        let previous=existingOrganization.trimmingCharacters(in:.whitespacesAndNewlines)
        let organizational=mapped ?? (key.isEmpty && known.contains(previous) ? previous : "")
        return Resolution(subdivision:subdivision,
                          organizationalUnit:organizational,
                          recognizedSite:true)
    }
